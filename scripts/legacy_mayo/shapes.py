import numpy as np
def _std(x):
    x=x-x.mean(); return x/x.std()
def make(name,rng,n):
    if name=='gaussian': x=rng.standard_normal(n)
    elif name=='laplace': x=rng.laplace(0,1,n)
    elif name=='uniform': x=rng.uniform(-1,1,n)
    elif name=='triangular': x=rng.triangular(-1,0,1,n)
    elif name=='logistic': x=rng.logistic(0,1,n)
    elif name=='t3': x=rng.standard_t(3,n)
    elif name=='t5': x=rng.standard_t(5,n)
    elif name=='t8': x=rng.standard_t(8,n)
    elif name=='t15': x=rng.standard_t(15,n)
    elif name=='t30': x=rng.standard_t(30,n)
    elif name=='lognorm025': x=np.exp(0.25*rng.standard_normal(n))
    elif name=='lognorm050': x=np.exp(0.50*rng.standard_normal(n))
    elif name=='lognorm100': x=np.exp(1.00*rng.standard_normal(n))
    elif name=='exponential': x=rng.exponential(1,n)
    elif name=='gumbel': x=rng.gumbel(0,1,n)
    elif name=='arcsine': x=rng.beta(0.5,0.5,n)
    elif name=='beta25': x=rng.beta(2,5,n)
    elif name=='mix_sep1': x=rng.standard_normal(n)+np.where(rng.random(n)<0.5,-0.5,0.5)
    elif name=='mix_sep2': x=rng.standard_normal(n)+np.where(rng.random(n)<0.5,-1.0,1.0)
    elif name=='mix_sep3': x=rng.standard_normal(n)+np.where(rng.random(n)<0.5,-2.0,2.0)
    elif name=='zeroinfl': x=np.where(rng.random(n)<0.60,0.0,rng.standard_normal(n))
    elif name=='bimodal_sym': x=np.where(rng.random(n)<0.5,-1.0,1.0)+0.15*rng.standard_normal(n)
    elif name=='bimodal_asy': x=np.where(rng.random(n)<0.80,rng.standard_normal(n),4.0+rng.standard_normal(n))
    elif name=='pareto3': x=(1+rng.pareto(3.0,n))
    elif name=='weibull15': x=rng.weibull(1.5,n)
    elif name=='chisq3': x=rng.chisquare(3,n)
    elif name=='contam10': x=np.where(rng.random(n)<0.01,10.,1.)*rng.standard_normal(n)
    elif name=='contam05': x=np.where(rng.random(n)<0.05,10.,1.)*rng.standard_normal(n)
    elif name=='scalemix15': x=np.exp(1.5*rng.standard_normal(n))*rng.standard_normal(n)
    elif name=='lognorm150': x=np.exp(1.5*rng.standard_normal(n))
    elif name=='t2': x=rng.standard_t(2,n)
    else: raise KeyError(name)
    return _std(x)
